"""Build frozen additive SQL from the reviewed Stage 3 column manifest.

This is an offline authoring tool, not an importer. Review generated SQL and
contract before use; Alembic never reads mutable documentation at runtime.
"""
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOCS = HERE.parent.parent / 'docs/backend-migration'
mapping = json.loads((DOCS / 'stage3-schema-mapping.json.md').read_text())
catalog = json.loads((DOCS / 'stage3-existing-pg-schema.json.md').read_text())
up, down, deferred = [], [], []
columns = {}
for c in catalog['columns']:
    columns.setdefault(c['table_name'], {})[c['column_name']] = c['data_type']
original = set(columns)
new = []
expected_columns = []
constraints = []
indexes = []


def q(value):
    return '"' + value.replace('"', '""') + '"'


def names(values):
    return ', '.join(map(q, values))


def name(kind, table, parts):
    stem = '_'.join([kind, table, *parts])
    return stem if len(stem) <= 60 else stem[:46] + '_' + hashlib.sha256(stem.encode()).hexdigest()[:12]


def change(sql, undo):
    up.append(sql + ';')
    down.insert(0, undo + ';')


def constraint(table, kind, parts, definition):
    key = name(kind, table, parts)
    assert not any(x['table'] == table and x['name'] == key for x in constraints), key
    change(f'ALTER TABLE {q(table)} ADD CONSTRAINT {q(key)} {definition}',
           f'ALTER TABLE {q(table)} DROP CONSTRAINT {q(key)}')
    constraints.append({'table': table, 'name': key, 'definition': definition})


def index(table, parts, unique=False, where=None):
    key = name('s4b_ux' if unique else 's4b_ix', table, parts)
    if any(x['name'] == key for x in indexes):
        return
    sql = f'CREATE {"UNIQUE " if unique else ""}INDEX {q(key)} ON {q(table)} ({names(parts)})'
    if where:
        sql += ' WHERE ' + where
    change(sql, f'DROP INDEX {q(key)}')
    indexes.append({'table': table, 'name': key, 'columns': parts, 'unique': unique, 'where': where})


def definition(c):
    col, typ, nullable, default = c
    result = f'{q(col)} {typ}'
    if default in {'identity', 'GENERATED BY DEFAULT AS IDENTITY'}:
        result += ' GENERATED BY DEFAULT AS IDENTITY'
    elif default != 'none':
        result += ' DEFAULT ' + default
    if nullable == 'NO':
        result += ' NOT NULL'
    return result


def add_column(table, c):
    assert c[0] not in columns[table], (table, c[0])
    change(f'ALTER TABLE {q(table)} ADD COLUMN {definition(c)}',
           f'ALTER TABLE {q(table)} DROP COLUMN {q(c[0])}')
    columns[table][c[0]] = c[1]
    expected_columns.append({'table': table, 'column': c[0], 'type': c[1], 'nullable': c[2], 'default': c[3]})


for t in mapping['tables']:
    if not t['new']:
        continue
    table = t['target']
    assert table not in columns
    cs = [('tenant_id', 'uuid', 'NO', 'none'), ('branch_id', 'uuid', 'NO', 'none'), ('version', 'bigint', 'NO', '1')]
    cs += [(c['target'], c['type'], c['nullable'], c['default']) for c in t['columns'] if c['action'] != 'CREDENTIAL EXCEPTION']
    pk = t['source_pk'] if t['source_pk'] == ['id'] else ['tenant_id', 'branch_id', *t['source_pk']]
    change(f'CREATE TABLE {q(table)} (' + ', '.join([definition(c) for c in cs] + [f'PRIMARY KEY ({names(pk)})']) + ')', f'DROP TABLE {q(table)}')
    columns[table] = {c[0]: c[1] for c in cs}
    expected_columns += [{'table': table, 'column': c[0], 'type': c[1], 'nullable': c[2], 'default': c[3]} for c in cs]
    new.append(table)

support_pks = {'command_receipts': ['tenant_id', 'branch_id', 'operation', 'request_key'],
               'import_source_records': ['tenant_id', 'source_sha256', 'source_table', 'source_key']}
for table, cs in mapping['additional_tables'].items():
    assert table not in columns
    pk = support_pks.get(table, ['id'])
    change(f'CREATE TABLE {q(table)} (' + ', '.join([definition(c) for c in cs] + [f'PRIMARY KEY ({names(pk)})']) + ')', f'DROP TABLE {q(table)}')
    columns[table] = {c[0]: c[1] for c in cs}
    expected_columns += [{'table': table, 'column': c[0], 'type': c[1], 'nullable': c[2], 'default': c[3]} for c in cs]
    new.append(table)

for t in mapping['tables']:
    if t['new']:
        continue
    for c in t['columns']:
        if c['action'].startswith('ADD'):
            if c['nullable'] == 'NO':
                deferred.append({'table': t['target'], 'column': c['target'], 'reason': 'Mandatory compatibility field/default requires native writer and status/financial projection agreement; do not fabricate values or break current inserts.'})
                continue
            add_column(t['target'], (c['target'], c['type'], c['nullable'], c['default']))
        elif 'widen numeric' in c['action']:
            # Widening preserves values; narrowing on rollback is only allowed with empty affected tables.
            old = next(x for x in catalog['columns'] if x['table_name'] == t['target'] and x['column_name'] == c['target'])
            old_type = old['data_type'] if old['data_type'] != 'numeric' else ('numeric' if old['numeric_precision'] is None else f"numeric({old['numeric_precision']},{old['numeric_scale']})")
            if old_type != 'numeric':
                change(f'ALTER TABLE {q(t["target"])} ALTER COLUMN {q(c["target"])} TYPE numeric', f'ALTER TABLE {q(t["target"])} ALTER COLUMN {q(c["target"])} TYPE {old_type}')
            expected_columns.append({'table': t['target'], 'column': c['target'], 'type': 'numeric', 'nullable': old['is_nullable'], 'default': old['column_default'], 'widened': True})

add_column('workshop_user_profiles', ('platform_user_id', 'uuid', 'YES', 'none'))
for table in ['legacy_receipts', 'legacy_gate_passes']:
    add_column(table, ('native_document_id', 'bigint', 'YES', 'none'))
add_column('material_requests', ('reservation_id', 'bigint', 'YES', 'none'))
for table, col in [('legacy_material_movements', 'legacy_job_card_id'), ('stock_ledger', 'legacy_job_card_id'), ('stock_ledger', 'legacy_material_row_id'), ('job_checklist_items', 'legacy_checked_by')]:
    add_column(table, (col, 'bigint', 'YES', 'none'))
    # Evidence only. No UPDATE/NULLIF conversion or fabricated parent is executed.
    constraint(table, 's4b_ck', [col], f'CHECK ({q(col)} IS NULL OR {q(col)} = 0)')

# Optimistic versions only on existing source-mapped mutable business tables.
for t in mapping['tables']:
    table = t['target']
    if 'version' not in columns[table]:
        add_column(table, ('version', 'bigint', 'NO', '1'))

scoped_keys = set()
def parent_key(table, cols):
    marker = (table, tuple(cols))
    if marker not in scoped_keys:
        wanted = ','.join(cols)
        existing = any(
            c['table_name']==table and c['contype'] in {'u','p'}
            and re.sub(r'[\s\"]','',c['definition']).split('(',1)[-1].rstrip(')')==wanted
            for c in catalog['constraints']
        )
        if not existing:
            constraint(table, 's4b_uk', cols, f'UNIQUE ({names(cols)})')
        scoped_keys.add(marker)


def fk(table, cols, parent, refs):
    if refs != ['id']:
        parent_key(parent, refs)
    constraint(table, 's4b_fk', cols, f'FOREIGN KEY ({names(cols)}) REFERENCES {q(parent)} ({names(refs)}) ON DELETE RESTRICT ON UPDATE NO ACTION')
    index(table, cols)


for table in new:
    fk(table, ['tenant_id'], 'tenants', ['id'])
    if 'branch_id' in columns[table]:
        fk(table, ['tenant_id', 'branch_id'], 'branches', ['tenant_id', 'id'])
    if 'version' in columns[table]:
        constraint(table, 's4b_ck', ['version'], 'CHECK (version > 0)')
    if 'id' in columns[table]:
        parent_key(table, ['tenant_id', 'branch_id', 'id'] if 'branch_id' in columns[table] else ['tenant_id', 'id'])

for t in mapping['tables']:
    table = t['target']
    for c in t['columns']:
        if c['target'] not in columns[table] or not c['relationship']:
            continue
        if not t['new'] and not c['action'].startswith('ADD'):
            continue  # Do not reinterpret existing UUID actors/native relationships.
        parent, key = c['relationship'].split('.')
        if columns[table][c['target']] != columns[parent][key]:
            deferred.append({'table': table, 'column': c['target'], 'reason': 'Identity type mapping requires review'})
            continue
        fk(table, ['tenant_id', 'branch_id', c['target']], parent, ['tenant_id', 'branch_id', key])
    if t['new']:
        for ui in t['unique_indexes']:
            parts = ['tenant_id', 'branch_id', *ui['columns']]
            if ui['columns'] == t['source_pk']:
                continue
            where = ui['sql'].split(' where ', 1)[1] if ui['sql'] and ' where ' in ui['sql'] else None
            index(table, parts, True, where)
        if {'created_at', 'id'} <= set(columns[table]):
            index(table, ['tenant_id', 'branch_id', 'created_at', 'id'])

fk('workshop_user_profiles', ['platform_user_id'], 'platform_users', ['id'])
parent_key('workshop_user_profiles', ['tenant_id', 'id'])
index('workshop_user_profiles', ['tenant_id', 'platform_user_id'], True, 'platform_user_id IS NOT NULL')
for table in ['legacy_receipts', 'legacy_gate_passes']:
    fk(table, ['tenant_id', 'branch_id', 'native_document_id'], 'financial_documents', ['tenant_id', 'branch_id', 'id'])
    index(table, ['tenant_id', 'branch_id', 'native_document_id'], True, 'native_document_id IS NOT NULL')
fk('material_requests', ['tenant_id', 'branch_id', 'reservation_id'], 'material_reservations', ['tenant_id', 'branch_id', 'id'])
index('material_requests', ['tenant_id', 'branch_id', 'reservation_id'], True, "reservation_id IS NOT NULL AND archived_at IS NULL")
fk('command_receipts', ['actor_id'], 'platform_users', ['id'])
fk('object_assets', ['created_by'], 'platform_users', ['id'])
fk('document_snapshots', ['tenant_id', 'branch_id', 'job_card_id'], 'job_cards', ['tenant_id', 'branch_id', 'id'])
fk('document_snapshots', ['tenant_id', 'template_version_id'], 'report_template_versions', ['tenant_id', 'id'])
fk('document_snapshots', ['tenant_id', 'branch_id', 'asset_id'], 'object_assets', ['tenant_id', 'branch_id', 'id'])
index('report_template_versions', ['tenant_id', 'template_key', 'version'], True)
index('report_template_versions', ['tenant_id', 'category'], True, 'active AND archived_at IS NULL')
index('object_assets', ['tenant_id', 'storage_key'], True)
index('object_assets', ['state', 'created_at'])
index('document_snapshots', ['tenant_id', 'branch_id', 'source_kind', 'source_id', 'snapshot_version'], True)
index('outbox_events', ['tenant_id', 'event_key'], True)
index('outbox_events', ['status', 'next_attempt_at'])
index('command_receipts', ['created_at'])
index('import_source_records', ['target_table', 'target_key'])
for table, label, expr in [
    ('advisor_attendance', 'present', 'present IN (0,1)'),
    ('object_assets', 'size', 'byte_size >= 0'),
    ('object_assets', 'sha', "sha256 ~ '^[0-9a-f]{64}$'"),
    ('object_assets', 'state', "state IN ('STAGED','READY','RETIRED')"),
    ('document_snapshots', 'availability', "availability IN ('UNAVAILABLE','READY') AND (availability <> 'READY' OR html IS NOT NULL OR asset_id IS NOT NULL)"),
    ('document_snapshots', 'version', 'snapshot_version > 0'),
    ('outbox_events', 'attempts', 'attempts >= 0'),
    ('outbox_events', 'status', "status IN ('PENDING','PROCESSING','DONE','FAILED')"),
    ('import_source_records', 'disposition', "disposition IN ('MAPPED','PRESERVED_HISTORY','CREDENTIAL_EXCLUDED','BLOCKED') AND (disposition <> 'BLOCKED' OR exception IS NOT NULL)"),
    ('import_source_records', 'hashes', "source_sha256 ~ '^[0-9a-f]{64}$' AND row_sha256 ~ '^[0-9a-f]{64}$'"),
    ('command_receipts', 'hash', "payload_sha256 ~ '^[0-9a-f]{64}$'"),
]:
    constraint(table, 's4b_ck', [label], f'CHECK ({expr})')

for c in expected_columns:
    if c['type'] == 'bigint' and c['column'] in {'done','washing_needed','document_available','passed'}:
        constraint(c['table'], 's4b_ck', [c['column']], f'CHECK ({q(c["column"])} IN (0,1))')
    if c['column'] == 'version' and c['table'] not in new:
        constraint(c['table'], 's4b_ck', ['version'], 'CHECK (version > 0)')

# New tables fail closed without trusted tenant/branch context. Existing policies stay untouched.
for table in new:
    predicate = "tenant_id = NULLIF(current_setting('workshopos.tenant_id', true), '')::uuid"
    if 'branch_id' in columns[table]:
        branch = "branch_id = ANY(COALESCE(NULLIF(current_setting('workshopos.branch_ids', true), ''), '{}')::uuid[])"
        predicate += ' AND (' + (f'branch_id IS NULL OR {branch}' if table == 'outbox_events' else branch) + ')'
    change(f'ALTER TABLE {q(table)} ENABLE ROW LEVEL SECURITY', f'ALTER TABLE {q(table)} DISABLE ROW LEVEL SECURITY')
    change(f'ALTER TABLE {q(table)} FORCE ROW LEVEL SECURITY', f'ALTER TABLE {q(table)} NO FORCE ROW LEVEL SECURITY')
    change(f'CREATE POLICY s4b_scope ON {q(table)} USING ({predicate}) WITH CHECK ({predicate})', f'DROP POLICY s4b_scope ON {q(table)}')
    change(f'GRANT SELECT, INSERT, UPDATE ON {q(table)} TO workshopos_runtime', f'REVOKE SELECT, INSERT, UPDATE ON {q(table)} FROM workshopos_runtime')
    if columns[table].get('id') == 'bigint':
        change(f'GRANT USAGE, SELECT ON SEQUENCE {q(table + "_id_seq")} TO workshopos_runtime', f'REVOKE USAGE, SELECT ON SEQUENCE {q(table + "_id_seq")} FROM workshopos_runtime')

contract = {'baseline_tables': sorted(original), 'new_tables': new, 'expected_table_count': len(columns), 'columns': expected_columns, 'constraints': constraints, 'indexes': indexes, 'deferred': deferred}
# PostgreSQL retains implicit numeric casts when altering integer back from numeric.
# Restore the original odometer CHECK exactly on the guarded empty-data downgrade.
down.insert(0, 'ALTER TABLE visits DROP CONSTRAINT visits_odo_reading_check;')
down.append('ALTER TABLE visits ADD CONSTRAINT visits_odo_reading_check CHECK ((odo_reading >= 0));')
(HERE/'versions').mkdir(exist_ok=True)
(HERE/'versions/0034_expand.sql').write_text('\n\n'.join(up)+'\n', encoding='utf-8')
(HERE/'versions/0034_contract.sql').write_text('\n\n'.join(down)+'\n', encoding='utf-8')
(HERE/'schema-contract.json').write_text(json.dumps(contract, indent=2)+'\n', encoding='utf-8')
print('Generated',len(up),'additive statements;',len(columns),'tables;',len(deferred),'deferred columns')
